 assert.equal(canOrderPersonalTruck(s),'orderAlreadyPending');
 assert.equal(tickDeliveries(s,t+1200005+179000).delivered,0);
 assert.equal(personalTruck(s),null);
 const delivered=tickDeliveries(s,t+1200005+180000);
 assert.equal(delivered.delivered,1);
 assert(delivered.machineryDelivered.some(x=>x.type==='drillTruckPersonal'));
