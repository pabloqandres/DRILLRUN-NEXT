import {test} from 'node:test';
import assert from 'node:assert/strict';
import * as T from '../dist/vendor/three.module.js';
import {World} from '../dist/scene.mjs';
import {ProductPreview} from '../dist/chapter/product-preview.mjs';

// Exercise the same real workshop geometry factory used by the game and catalog,
// without constructing WebGL or touching browser storage / the current save.
function workshopFixture(){
 const snapshot={boxes:0,pads:0};
 const fake={
  scene:new T.Group(),colliders:[],walkSurfaces:[],labels:[],
  box(group){snapshot.boxes++;const item=new T.Group();item.material={};group.add(item);return item;},
  cyl(group){const item=new T.Group();group.add(item);return item;},
  pad(){snapshot.pads++;},
  shelf(){},toolbox(){},sign(){},
 };
 return {fake,snapshot};
}

test('workshop catalog preview creates real factory architecture without altering live world or HSEC collision data',()=>{
 const {fake,snapshot}=workshopFixture();
 const priorScene=fake.scene.children.length;
 const preview=World.prototype.makeWorkshop.call(fake,true);
 assert.equal(preview.name,'DR-BLD-002 · Taller de mantenimiento');
 assert(snapshot.boxes>80,'building detail meshes are generated by the same factory');
 assert.equal(fake.scene.children.length,priorScene,'no duplicate workshop in playable world');
 assert.equal(snapshot.pads,0,'preview never lays a second gameplay pad');
 assert.equal(fake.colliders.length,0,'preview must never add world blockers');
 assert.equal(fake.walkSurfaces.length,0,'preview must never modify walk surfaces');
 assert.equal(fake.labels.length,0,'preview must never add map markers');
 assert.equal(fake.workshopModel,undefined,'preview cannot replace real workshop');
});

test('installed workshop keeps its collision walls and existing interaction zones',()=>{
 const {fake,snapshot}=workshopFixture();
 const built=World.prototype.makeWorkshop.call(fake,false);
 assert.equal(fake.scene.children[0],built);
 assert.equal(fake.workshopModel,built);
 assert.equal(snapshot.pads,1);
 assert.equal(fake.colliders.length,5);
 assert.equal(fake.walkSurfaces.length,1);
 assert.equal(fake.labels.length,1);
});

test('building thumbnail clones mesh buffers, never destroying meshes in the live world',()=>{
 const geometry=new T.BoxGeometry(1,1,1);
 const source=new T.Group(),mesh=new T.Mesh(geometry,new T.MeshStandardMaterial({color:0x334455}));
 source.add(mesh);
 const harness={scene:new T.Scene(),releaseModel(){this.model?.removeFromParent();this.model=null;},draw(){this.drawCount=(this.drawCount||0)+1;}};
 ProductPreview.prototype.setBuilding.call(harness,[source]);
 assert.notEqual(harness.model.children[0].children[0].geometry,geometry);
 assert.equal(source.children[0].geometry,geometry);
 assert.equal(source.parent,null);
 assert.equal(harness.drawCount,1);
 assert(harness.model.children[0].children[0].geometry.attributes.position.count>0);
});

test('real new building thumbnail bindings are available from the same catalog module',async()=>{
 const {BuilderUI}=await import('../dist/chapter/builder-ui.mjs');
 assert.equal(typeof BuilderUI.prototype.getWorkshopThumbnail,'function');
 assert.equal(typeof BuilderUI.prototype.getOfficeThumbnail,'function');
});
