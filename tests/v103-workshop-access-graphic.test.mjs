test('V103 graphics: real workshop art, native capacity ring, 3 service stations, compact state',()=>{
 const s=make(2),before=JSON.stringify(s);
 const html=draw(s);
 assert(html.includes('assets/faena-v82/workshop.webp'));
 assert(html.includes('ws103CapacityDial'));
 assert(html.includes('14</strong><small>LIBRES'));
 assert.equal((html.match(/class="ws103Tile /g)||[]).length,3);
 for(const text of ['Reafilado de bits','Servicio de martillos','Kits de servicio','Gestión de equipos DTH'])
  assert(html.includes(text),text);
 assert(html.includes('class="ws103Complete"'));
 assert(!html.includes('ws103UpgradeButton'));
 assert(!/<header\b/.test(html),'nested header triggered legacy global HUD collision');
 assert.equal(JSON.stringify(s),before,'graphics must be read-only');
});
test('V103 upgrade remains original single purchase CTA; real countdown when building',()=>{
 const s=make(1);
 let html=draw(s);
 assert(html.includes('data-faena-workshop-upgrade'));
 assert(html.includes('8.000'));
 assert(html.includes('05:00'));
 s.workshop.upgrade={started:now,ends:now+300000,targetLevel:2,paid:8000};
 assert.equal(workshopConstructionReadout(s,now+150000).progress,50);
 html=draw(s);
 assert(html.includes('data-ws102-progress'));
 assert(html.includes('05:00'));
 assert(!html.includes('data-faena-workshop-upgrade'));
 assert(html.includes('data-ws102-remaining'));
 assert(html.includes('data-ws102-percent'));
});
