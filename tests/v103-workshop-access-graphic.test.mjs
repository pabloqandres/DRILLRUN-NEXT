import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newGame} from '../dist/chapter/state.mjs';
import {workshopReady,workshopHasExtension,nearWorkshopDoor,workshopTapZone,WORKSHOP_DOORS} from '../dist/chapter/workshop-world-access-v103.mjs';
import {renderWorkshopVisualV103} from '../dist/chapter/workshop-v103-view.mjs';
import {workshopConstructionReadout} from '../dist/chapter/workshop-progress-v102.mjs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const now=Date.UTC(2026,10,13,12,0,0);
const icon=name=>'<svg class="uiIcon" data-icon="'+name+'"></svg>';
const money=n=>'🪙 '+Number(n).toLocaleString('es-CL');
const make=(level=1)=>{
 const s=newGame('es','operator01',now);
 s.workshop={status:'built',level};
 s.cash=95458;
 s.toolInventory=[];s.spentMaterials=[];
 return s;
};
const draw=s=>renderWorkshopVisualV103(s,{icon,money,m4:()=>'<span>M4 original</span>',now});
test('V103: door action recognizes both original Workshop and real extension entrance',()=>{
 const s=make(1);
 assert.equal(workshopReady(s),true);
 assert.equal(workshopHasExtension(s),false);
 assert.equal(nearWorkshopDoor(s,{x:-6.8,z:-5.4}),'base');
 assert.equal(nearWorkshopDoor(s,WORKSHOP_DOORS.extension),null);
 s.workshop.level=2;
 assert.equal(workshopHasExtension(s),true);
 assert.equal(nearWorkshopDoor(s,WORKSHOP_DOORS.extension),'extension');
 assert.equal(nearWorkshopDoor(s,{x:-7.6,z:-5.8}),'base');
 assert.equal(nearWorkshopDoor(s,{x:5,z:8}),null);
});
test('V103: L2 mesh tap or courtyard floor selects same Workshop; not from across map',()=>{
 const s=make(2),player={x:-2.45,z:-6.05};
 assert.equal(workshopTapZone(s,{x:-2.4,z:-9.2},player),'extension');
 assert.equal(workshopTapZone(s,null,player,{extensionMeshHit:true}),'extension');
 assert.equal(workshopTapZone(s,{x:-7.6,z:-9.3},{x:-7.6,z:-5.8}),'base');
 assert.equal(workshopTapZone(s,null,{x:60,z:60},{extensionMeshHit:true}),null);
 s.workshop.level=1;
 assert.equal(workshopTapZone(s,{x:-2.4,z:-9.2},player),null);
 s.workshop.status='building';
 assert.equal(nearWorkshopDoor(s,WORKSHOP_DOORS.base),null);
 assert.equal(workshopTapZone(s,{x:-7.6,z:-9.3},{x:-7.6,z:-5.8}),null);
});
