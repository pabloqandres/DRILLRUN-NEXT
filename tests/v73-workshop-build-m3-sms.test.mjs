import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newGame} from '../dist/chapter/state.mjs';
import {WORKSHOP_L1_SECONDS,WORKSHOP_LEVELS,WORKSHOP_L1_COST,buildWorkshop,finishWorkshopConstruction,migrateWorkshopL1Construction,workshopL1Progress} from '../dist/mission3/inventory.mjs';
import {NARRATIVE_STRINGS} from '../dist/chapter/narrative-strings.mjs';
import {CONTRACT_TEMPLATES} from '../dist/mission3/contracts.mjs';
const source=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const start=Date.UTC(2026,10,11,13,0,0);
const fixture=()=>{
 const s=newGame('es','operator01',start);
 s.mission3={phase:'workshop'};s.hsec={completedAt:start};s.office.level=2;s.cash=50000;
 return s;
};
test('Workshop L1 takes exactly 01:30 without changing upgrade duration or price',()=>{
 assert.equal(WORKSHOP_L1_SECONDS,90);
 assert.equal(WORKSHOP_LEVELS[1].constructionSeconds,300);
 const s=fixture(),cash=s.cash,w=buildWorkshop(s,start);
 assert.equal(w.status,'building');
 assert.equal(w.ends-w.started,90000);
 assert.equal(s.cash,cash-WORKSHOP_L1_COST);
 assert.equal(s.ledger.filter(x=>x.key==='workshopBuild').length,1);
 assert.equal(workshopL1Progress(s,start).percent,0);
 assert.equal(workshopL1Progress(s,start+45000).percent,50);
 assert.equal(workshopL1Progress(s,start+45000).remaining,45000);
 assert.equal(finishWorkshopConstruction(s,start+89999),false);
 assert.equal(w.status,'building');
 assert.equal(finishWorkshopConstruction(s,start+90000),true);
 assert.equal(w.status,'built');
 assert.equal(finishWorkshopConstruction(s,start+90001),false);
 assert.equal(workshopL1Progress(s,start+90001),null);
});
test('Old unfinished 00:30 workshop is extended without charging or restarting; finished remains completed',()=>{
 const s=fixture(),w=buildWorkshop(s,start);
 const cash=s.cash,transactions=s.ledger.length;
 w.ends=w.started+30000;
 assert.equal(migrateWorkshopL1Construction(s),true);
 assert.equal(migrateWorkshopL1Construction(s),false);
 assert.equal(w.started,start);
 assert.equal(w.ends,start+90000);
 assert.equal(s.cash,cash);
 assert.equal(s.ledger.length,transactions);
 w.status='built';
 w.ends=start+30000;
 assert.equal(migrateWorkshopL1Construction(s),false);
 assert.equal(w.status,'built');
 assert.equal(w.ends,start+30000);
});
