import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {newGame} from '../dist/chapter/state.mjs';
import {renderM3App} from '../dist/mission3/phone-apps.mjs';
import {renderPatioApp} from '../dist/mission5/patio-ui.mjs';
import {startPatio,finishPatio} from '../dist/mission5/patio-state.mjs';
import {hirePatioStaff,mission5Objectives} from '../dist/mission5/patio-staff.mjs';
import {playerNeedsGateOpen,gateShouldOpen,barrierBlocksPlayer} from '../dist/mission5/gate-control.mjs';

const now=Date.UTC(2026,10,10,17);
const fmt=n=>Number(n).toLocaleString('es-CL');
const icon=x=>'['+x+']';
const text=x=>x;
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
function activeYard(){
 const s=newGame('es','operador',now);
 s.cash=100000;
 s.mission4={phase:'complete'};
 s.narrative={messages:[],accepted:['m5'],rewardsCollected:[]};
 s.mission3={phase:'complete'};
 startPatio(s,now);
 finishPatio(s,now+1200000);
 return s;
}
test('V49 M5 hires live in Personal and still advance mission objectives',()=>{
 const s=activeYard();
 const personnel=renderM3App('m3-personnel',s,text,fmt,icon,{});
 assert.match(personnel,/Logística · Patio de Maquinarias/);
 assert.match(personnel,/data-hire-patio="m5-gate-security"/);
 assert.match(personnel,/data-hire-patio="m5-warehouse-tech"/);
 assert.match(personnel,/1\.800/);
 assert.match(personnel,/2\.200/);
 const patio=renderPatioApp(s,fmt,icon,now+1200000);
 assert.doesNotMatch(patio,/data-m5-action="hire"/);
 assert.match(patio,/data-app="m3-personnel"/);
 assert.equal(mission5Objectives(s).filter(o=>o.done).length,1);
 hirePatioStaff(s,'m5-gate-security',now+1200001);
 assert.equal(mission5Objectives(s).filter(o=>o.done).length,2);
 const rerender=renderM3App('m3-personnel',s,text,fmt,icon,{});
 assert.match(rerender,/Contratado/);
 assert.match(rerender,/data-hire-patio="m5-warehouse-tech"/);
 hirePatioStaff(s,'m5-warehouse-tech',now+1200002);
 assert.equal(mission5Objectives(s).filter(o=>o.done).length,3);
 assert.equal(s.cash,51000,'45k yard and 4k staffing, no phantom payout');
 assert.equal(s.ledger.filter(x=>x.key==='m5Personnel').length,2);
});
test('V49 player-only gate sensor is symmetric on either side and releases after crossing',()=>{
 const side1={x:-19.4,z:-14},side2={x:-28.6,z:-14};
 assert.equal(playerNeedsGateOpen(side1),true);
 assert.equal(playerNeedsGateOpen(side2),true);
 assert.equal(playerNeedsGateOpen({x:-10,z:-14}),false);
 assert.equal(gateShouldOpen({position:side1}),true);
 assert.equal(gateShouldOpen({position:side2}),true);
 assert.equal(gateShouldOpen({position:{x:-8,z:-14},routeInUse:true}),true);
 assert.equal(gateShouldOpen({position:{x:-8,z:-14},vehicleNear:true}),true);
 assert.equal(gateShouldOpen({position:{x:-8,z:-14}}),false);
 assert.equal(playerNeedsGateOpen({x:-18.0,z:-14},true),true);
 assert.equal(playerNeedsGateOpen({x:-16,z:-14},true),false);
 assert.equal(barrierBlocksPlayer(0),true);
 assert.equal(barrierBlocksPlayer(-.6),true);
 assert.equal(barrierBlocksPlayer(-1.3),false);
});
